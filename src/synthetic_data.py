# ---------------------------------------------------------------------------
# Spectrum synthesis
# ---------------------------------------------------------------------------

def lorentzian(x, center, amplitude, hwhm):
    """Lorentzian (Cauchy) lineshape."""
    return amplitude * hwhm ** 2 / ((x - center) ** 2 + hwhm ** 2)


def synthesize_spectrum(peaks, grid=STANDARD_GRID, rng=None):
    """
    Generate one Raman spectrum from a peak table.

    Each peak is (center_cm⁻¹, relative_amplitude, half_width_cm⁻¹).
    Random variations are applied to simulate measurement noise.
    """
    if rng is None:
        rng = np.random.default_rng()

    spectrum = np.zeros(len(grid))

    for center, amplitude, hwhm in peaks:
        # Small random calibration shift (±3 cm⁻¹)
        c = center + rng.uniform(-3, 3)
        # Random amplitude variation (±20%)
        a = amplitude * rng.uniform(0.80, 1.20)
        # Random width variation (±15%)
        w = hwhm * rng.uniform(0.85, 1.15)
        spectrum += lorentzian(grid, c, a, w)

    # Random polynomial baseline (fluorescence residual)
    if rng.random() < 0.8:
        t = np.linspace(0, 1, len(grid))
        b_amp = rng.uniform(0.0, 0.25)
        b_shape = rng.uniform(-1, 1)
        spectrum += b_amp * (t + b_shape * t ** 2)

    # Gaussian noise
    noise_level = rng.uniform(0.005, 0.03)
    spectrum += rng.normal(0.0, noise_level, len(grid))
    spectrum = np.clip(spectrum, 0.0, None)

    # Normalise
    peak_val = spectrum.max()
    if peak_val > 0:
        spectrum /= peak_val
    else:
        return None

    return spectrum.astype(np.float32)


