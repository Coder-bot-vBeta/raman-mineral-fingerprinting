# Dataset builder
# ---------------------------------------------------------------------------

def generate_dataset(
    data_dir="data",
    n_per_mineral=25,
    seed=42,
    min_grid_coverage=0.30,
):
    """
    Generate synthetic Raman training data and save to data/processed/.

    Parameters
    ----------
    n_per_mineral : int
        Number of synthetic spectra per mineral.
    min_grid_coverage : float
        Fraction of the standard grid that must be covered by at least one
        peak's support; discards minerals with peaks entirely outside range.
    """
    processed_dir = Path(data_dir) / "processed"
    processed_dir.mkdir(parents=True, exist_ok=True)

    rng = np.random.default_rng(seed)

    valid_minerals = sorted(MINERAL_PEAKS.keys())

    print(f"Generating {n_per_mineral} spectra × {len(valid_minerals)} minerals "
          f"= {n_per_mineral * len(valid_minerals)} total spectra...")

    label_map = {name: i for i, name in enumerate(valid_minerals)}

    X_list, y_list = [], []

    for name in valid_minerals:
        peaks = MINERAL_PEAKS[name]
        label = label_map[name]
        generated = 0
        attempts = 0
        while generated < n_per_mineral and attempts < n_per_mineral * 5:
            attempts += 1
            s = synthesize_spectrum(peaks, rng=rng)
            if s is not None:
                X_list.append(s)
                y_list.append(label)
                generated += 1
        if generated < n_per_mineral:
            print(f"  WARNING: only {generated}/{n_per_mineral} spectra for {name}")

    X = np.array(X_list, dtype=np.float32)
    y = np.array(y_list, dtype=np.int64)

    np.save(processed_dir / "X.npy", X)
    np.save(processed_dir / "y.npy", y)

    labels_df = pd.DataFrame({
        "label": range(len(valid_minerals)),
        "mineral": valid_minerals,
    })
    labels_df.to_csv(processed_dir / "label_map.csv", index=False)

    # Reference spectra — noiseless mean-like spectrum (3 samples averaged)
    ref = np.zeros((len(valid_minerals), N_POINTS), dtype=np.float32)
    for name in valid_minerals:
        peaks = MINERAL_PEAKS[name]
        idx = label_map[name]
        samples = [synthesize_spectrum(peaks, rng=rng) for _ in range(3)]
        samples = [s for s in samples if s is not None]
        if samples:
            mean_s = np.mean(samples, axis=0)
            peak_val = mean_s.max()
            ref[idx] = mean_s / peak_val if peak_val > 0 else mean_s

    np.save(processed_dir / "reference_spectra.npy", ref)

    print(f"\nSynthetic dataset ready:")
    print(f"  Spectra: {len(X)}")
    print(f"  Mineral classes: {len(valid_minerals)}")
    print(f"  Grid: {STANDARD_GRID[0]:.0f}-{STANDARD_GRID[-1]:.0f} cm-1 "
          f"({N_POINTS} points)")

    return X, y, label_map


if __name__ == "__main__":
    generate_dataset()
